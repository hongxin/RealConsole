#!/usr/bin/env bash
# Phase 4.2 P1 功能测试脚本
# 测试：拼写纠错 + 建议缓存过期机制

set -e

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "🧪 Phase 4.2 P1 功能测试"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

# 检查 realconsole 是否已安装
if ! command -v realconsole &> /dev/null; then
    echo "❌ realconsole 未安装或不在 PATH 中"
    echo "请运行: make install"
    exit 1
fi

echo "✓ realconsole 已安装"
echo ""

# 获取版本信息
VERSION=$(realconsole --version 2>&1 || echo "unknown")
echo "📦 版本: $VERSION"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📋 测试场景说明"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

cat <<'EOF'
本测试需要手动在 RealConsole 中执行以下场景：

┌─────────────────────────────────────────────┐
│ 场景 1: 拼写纠错功能                         │
└─────────────────────────────────────────────┘

1.1 测试 cargo 拼写错误
  输入: !cago build
  预期: 建议 "cargo build"（距离=1，高分）

1.2 测试 git 拼写错误
  输入: !gi status
  预期: 建议 "git status"（距离=1，高分）

1.3 测试 npm 拼写错误
  输入: !npn install
  预期: 建议 "npm install"（距离=1，高分）

1.4 测试不存在的命令（距离太大）
  输入: !abcdefgh
  预期: 没有拼写建议（或分数很低）

1.5 测试正确的命令
  输入: !ls
  预期: 不应该有拼写建议（命令正确）


┌─────────────────────────────────────────────┐
│ 场景 2: 建议缓存过期机制                     │
└─────────────────────────────────────────────┘

2.1 生成建议并立即使用（新鲜缓存）
  输入: /suggest
  输入: 1
  预期: 立即执行第一个建议

2.2 再次使用缓存（仍然新鲜）
  输入: 2
  预期: 执行第二个建议（如果存在）

2.3 检查缓存状态
  - 在 2.5 分钟内：缓存新鲜，可以使用
  - 2.5-5 分钟：缓存陈旧，可能提示
  - 5 分钟后：缓存过期，自动清除


┌─────────────────────────────────────────────┐
│ 场景 3: 数字快速执行（Phase 4.2 集成测试）   │
└─────────────────────────────────────────────┘

3.1 命令失败触发建议
  输入: !cago test
  预期: 自动显示建议（包括拼写纠正的 "cargo test"）

3.2 快速执行建议
  输入: 1
  预期: 立即执行 "cargo test"

3.3 无效的建议编号
  输入: 99
  预期: 提示 "无效的建议编号"


┌─────────────────────────────────────────────┐
│ 场景 4: 优先级测试（拼写 vs 错误模式）       │
└─────────────────────────────────────────────┘

4.1 拼写错误优先
  输入: !cago build
  预期: 第一个建议是 "cargo build"（拼写纠正）

4.2 错误模式（非拼写错误）
  输入: !git status  (在非 Git 仓库)
  预期: 建议 "git init" 或 "git clone"（错误模式匹配）

EOF

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "🚀 准备启动 RealConsole..."
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
echo "提示："
echo "  - 按照上面的场景逐一测试"
echo "  - 观察建议的内容和分数"
echo "  - 验证缓存过期行为"
echo "  - 测试完成后输入 'exit' 退出"
echo ""
echo "按 Enter 键启动 RealConsole..."
read

# 启动 realconsole
echo ""
echo "启动 realconsole..."
echo ""

realconsole
